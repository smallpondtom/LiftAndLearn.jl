export opinf


"""
$(SIGNATURES)

Infer the reduced operators of a lifted system by Lift & Learn (LnL).

If `options.optim.reproject` is `true`, the derivative data is generated by reprojection
through the lifting map (see the `lifting` method of `reproject`); otherwise it is
approximated from `W` by finite differences with `time_derivative_approx`, and the state,
input and output data are restricted to the time indices of the scheme.

## Arguments
- `W::AbstractArray`: lifted state snapshot matrix of size ``n \\times K`` (rows = lifted state, columns = time).
- `Vn::AbstractArray`: basis of the lifted state of size ``n \\times r`` (e.g. from `lifted_basis`).
- `lm::lifting`: lifting map.
- `full_op::Operators`: full-order operators of the original (unlifted) model (used for reprojection).
- `options::AbstractOption`: OpInf options (typically an `LSOpInfOption`).

## Keyword Arguments
- `U::AbstractArray=zeros(1,1)`: input data (fat matrices are transposed to tall).
- `Y::AbstractArray=zeros(1,1)`: output data (fat matrices are transposed to tall).

## Returns
- `op::Operators`: the inferred reduced operators.

## Notes
- Use the unlifted `opinf(X, Vn, options)` method if reprojection is not needed.
- With reprojection, `U` must have ``K`` time samples (pass zeros for an autonomous
  system); the default `zeros(1,1)` only works for ``K = 1``.
"""
function opinf(W::AbstractArray, Vn::AbstractArray, lm::lifting, full_op::Operators, 
               options::AbstractOption; U::AbstractArray=zeros(1,1), 
               Y::AbstractArray=zeros(1,1))::Operators
    Ut = fat2tall(U)
    Yt = fat2tall(Y)

    # Project
    What = Vn' * W
    What_t = W' * Vn

    # Generate R matrix from finite difference if not provided as a function argument
    if options.optim.reproject == true
        Rt = reproject(What, Vn, Ut, lm, full_op, options)
    else
        Wdot, idx = time_derivative_approx(W, options)
        What = Vn' * W[:, idx]  # fix the index of states
        What_t = What'
        Ut = iszero(Ut) ? [0.0] : Ut[idx, :]  # fix the index of inputs
        Yt = iszero(Yt) ? [0.0] : Yt[idx, :]  # fix the index of outputs
        Rt = Wdot' * Vn
    end

    D, dims, op_symbols = get_data_matrix(What, What_t, Ut, options, verbose=true)
    op = leastsquares_solve(D, Rt, Yt, What_t, dims, op_symbols, options)

    return op
end



"""
$(SIGNATURES)

Generate the derivative data of a lifted system by reprojection.

For each snapshot the lifted state is reconstructed as ``\\mathbf{V}\\hat{\\mathbf{x}}``; the
time derivative of the original variables is evaluated with the full-order model `op`,
and the time derivative of the additional lifted variables is approximated by a forward
Euler step of size `options.data.Δt` through the lifting map `lm.mapNL`. The result is
projected back onto `V`.

## Arguments
- `Xhat::AbstractArray`: reduced lifted state snapshot matrix of size ``r \\times K`` (columns = snapshots).
- `V::AbstractArray`: basis of the lifted state of size ``(N_l \\cdot gp) \\times r``.
- `Ut::AbstractArray`: tall input data matrix of size ``K \\times m``.
- `lm::lifting`: lifting map.
- `op::Operators`: full-order operators of the original (unlifted) model. The nonlinear part is
  `op.f` if a custom function was supplied (e.g. the cubic term of FitzHugh–Nagumo), otherwise the
  default built from the polynomial and bilinear operators of `op`.
- `options::AbstractOption`: OpInf options (uses `vars.N`, `vars.N_lift` and `data.Δt`).

## Returns
- `Rt::Matrix`: reprojected derivative data ``\\mathbf{R}^\\top`` of size ``K \\times r``.
"""
function reproject(Xhat::AbstractArray, V::AbstractArray, Ut::AbstractArray,
    lm::lifting, op::Operators, options::AbstractOption)::Matrix

    tmp = size(V, 1)
    n = tmp / options.vars.N_lift
    dt = options.data.Δt
    r, K = size(Xhat)
    Rt = zeros(K, r)  # Left hand side of the regression problem

    # Use the user-supplied nonlinear function if given, else the default built from the operators
    fnl = _nonlinear_function(op)
    f = (x, u) -> op.A * x .+ op.B * u .+ op.K .+ fnl(x,u)

    for i in 1:K  # loop thru all data
        x = Xhat[:, i]  # julia automatically makes into column vec after indexing (still xrow-tcol)
        xrec = V * x
        states = f(xrec[1:Int(options.vars.N * n), :], Ut[i, :])

        # Lifted variables
        next = [xrec[Int((j - 1) * n + 1):Int(j * n)] + dt * states[Int((j - 1) * n + 1):Int(j * n)] for j in 1:options.vars.N]
        z = lm.mapNL(next)  # map the nonlifted variables to the lifting functions
        dz = (z - xrec[(Int(options.vars.N * n)+1):Int(options.vars.N_lift * n)]) ./ options.data.Δt

        # Combine the original and lifted variables
        states = vcat(states, dz)

        # Project to obtain derivative data
        Rt[i, :] = V' * states
    end
    return Rt
end